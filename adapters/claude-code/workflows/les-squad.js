export const meta = {
  name: "les-squad",
  description: "LES Squad rung: Architecture plans, the owning department delivers, QA and Review verify in parallel, Challenge tries to refute, and fixes loop at most twice",
  whenToUse: "R1 multi-step or R2 work the Lead has classified. Args: {task, acceptance, risk, owner?, paths?, security?}. Never for R3.",
  phases: [
    { title: "Plan", detail: "les-architecture" },
    { title: "Deliver", detail: "owning department" },
    { title: "Verify", detail: "les-qa, les-review, les-security when flagged" },
    { title: "Challenge", detail: "les-challenge refutes findings and the delivery claim" }
  ]
};
// <!-- les-team: generated by `les connect` or `les team on`; `les team off` removes it. -->
// Policy: ~/.les-agents/policies/team.md. The Lead still reports the terminal status; this script returns evidence only.

const a = (typeof args === "string" ? JSON.parse(args) : args) ?? {};
if (!a.task || !a.acceptance) throw new Error("les-squad needs args.task and args.acceptance");
if (a.risk === "R3") throw new Error("R3 needs a human approval gate immediately before the action; run the departments step by step instead");
const writers = ["engineering", "frontend", "devops", "product", "architecture"];
const owner = a.owner ?? "engineering";
if (!writers.includes(owner)) throw new Error("args.owner must be one of: " + writers.join(", "));
// One delivery plus at most two fix rounds.
const MAX_ROUNDS = 3;

const brief = (skillHint, extra = []) => [
  "LES brief.",
  "Objective: " + a.task,
  "Acceptance: " + (Array.isArray(a.acceptance) ? a.acceptance.join("; ") : a.acceptance),
  "Risk: " + (a.risk ?? "R2"),
  a.paths ? "Owned paths: " + [].concat(a.paths).join(", ") : "",
  "Skill: " + skillHint,
  ...extra
].filter(Boolean).join("\n");

const STATUS = { type: "string", enum: ["COMPLETE", "BLOCKED", "PENDING_USER_ACTION", "FAILED", "SKIPPED"] };
const FINDING = {
  type: "object",
  properties: {
    severity: { type: "string", enum: ["blocker", "high", "medium", "low"] },
    location: { type: "string" },
    problem: { type: "string" },
    evidence: { type: "string" },
    fix: { type: "string" }
  },
  required: ["severity", "location", "problem", "evidence"]
};
const PLAN = {
  type: "object",
  properties: { status: STATUS, steps: { type: "array", items: { type: "string" } }, checks: { type: "array", items: { type: "string" } }, ownedPaths: { type: "array", items: { type: "string" } } },
  required: ["status", "steps", "checks"]
};
const REPORT = {
  type: "object",
  properties: { status: STATUS, changedPaths: { type: "array", items: { type: "string" } }, checks: { type: "array", items: { type: "string" } }, residualRisk: { type: "string" } },
  required: ["status", "changedPaths", "checks"]
};
const FINDINGS = { type: "object", properties: { status: STATUS, findings: { type: "array", items: FINDING }, coverage: { type: "string" } }, required: ["status", "findings"] };
const VERDICT = { type: "object", properties: { verdict: { type: "string", enum: ["holds", "refuted"] }, evidence: { type: "string" } }, required: ["verdict", "evidence"] };

phase("Plan");
const plan = await agent(brief("les-planning", ["Return the plan, the acceptance checks to run, and the paths the writer owns. Do not edit files."]), { agentType: "les-architecture", schema: PLAN, phase: "Plan" });
if (!plan || plan.status !== "COMPLETE") return { status: plan?.status ?? "FAILED", stage: "plan", plan };

let delivery;
let surviving = [];
const rounds = [];
for (let round = 1; round <= MAX_ROUNDS; round += 1) {
  const fixes = surviving.length ? ["Fix these verified findings, nothing else:", JSON.stringify(surviving, null, 1)] : [];
  const owned = plan.ownedPaths?.length ? ["Plan-owned paths: " + plan.ownedPaths.join(", ")] : [];
  delivery = await agent(brief(owner === "engineering" ? "les-feature-delivery or les-bug-fixing, test first" : "your department skill", ["Plan:", ...plan.steps, "Checks: " + plan.checks.join("; "), ...owned, ...fixes]), { agentType: "les-" + owner, schema: REPORT, phase: "Deliver", label: "deliver round " + round });
  if (!delivery || delivery.status !== "COMPLETE") return { status: delivery?.status ?? "FAILED", stage: "deliver", round, plan, delivery, rounds };

  const target = "Change under review: " + delivery.changedPaths.join(", ") + ". Writer checks: " + delivery.checks.join("; ");
  const reviewers = [
    ["les-qa", "les-verification: run the acceptance checks and report exit status"],
    ["les-review", "les-review"],
    ...(a.security ? [["les-security", "les-security-review"]] : [])
  ];
  const verify = await parallel(reviewers.map(([agentType, skill]) => () =>
    agent(brief(skill, [target, "Read-only. Report findings with location and evidence."]), { agentType, schema: FINDINGS, phase: "Verify", label: agentType + " round " + round })));
  // A missing, BLOCKED, or PENDING_USER_ACTION reviewer stops the run; FAILED is a fixable result; SKIPPED is allowed.
  const blockedReviewers = reviewers.filter((_, index) => !verify[index] || ["BLOCKED", "PENDING_USER_ACTION"].includes(verify[index].status)).map(([agentType]) => agentType);
  if (blockedReviewers.length) {
    rounds.push({ round, blockedReviewers });
    return { status: "BLOCKED", stage: "verify", plan, delivery, rounds };
  }
  const failedChecks = reviewers.flatMap(([agentType], index) => verify[index].status === "FAILED" && !verify[index].findings.length
    ? [{ severity: "high", location: agentType, problem: "checks failed without a located finding", evidence: verify[index].coverage ?? "status FAILED" }]
    : []);
  const all = verify.flatMap((report) => report.findings);
  const low = all.filter((finding) => finding.severity === "low");

  phase("Challenge");
  const serious = all.filter((finding) => finding.severity !== "low");
  const judged = await parallel([
    ...serious.map((finding) => () =>
      agent(brief("les-challenge", ["Try to refute this finding from the code. Refute only with evidence; when unsure, verdict holds.", JSON.stringify(finding, null, 1)]), { agentType: "les-challenge", schema: VERDICT, phase: "Challenge", label: "finding: " + finding.location })
        .then((verdict) => (verdict?.verdict === "refuted" ? null : finding))),
    () => agent(brief("les-challenge", [target, "Claim: the change meets every acceptance condition. Try to prove it wrong."]), { agentType: "les-challenge", schema: VERDICT, phase: "Challenge", label: "delivery claim" })
      .then((verdict) => verdict?.verdict === "holds" ? null : { severity: "high", location: delivery.changedPaths.join(", "), problem: verdict ? "delivery claim refuted" : "delivery claim was not challenged", evidence: verdict?.evidence ?? "challenge agent returned no verdict" })
  ]);
  surviving = [...failedChecks, ...judged.filter(Boolean)];
  rounds.push({ round, findings: surviving, low });
  log("round " + round + ": " + surviving.length + " surviving finding(s), " + low.length + " low");
  if (!surviving.length) return { status: "COMPLETE", plan, delivery, rounds };
}
return { status: "FAILED", stage: "fix-loop", reason: "findings survive after " + (MAX_ROUNDS - 1) + " fix rounds", plan, delivery, rounds };
